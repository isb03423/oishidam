-- 회원
CREATE TABLE IF NOT EXISTS members (
    member_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT, -- 이메일 암호문
    email_lookup VARCHAR(72), -- 이메일의 HMAC 조회값. 유일성은 개인정보 이관 시 적용한다.
    email_verified_at TIMESTAMP WITHOUT TIME ZONE, -- 이메일 소유가 확인된 시간
    password VARCHAR(255), -- 비밀번호 해시; 소셜 전용 계정은 없을 수 있음
    name TEXT NOT NULL, -- 회원 이름 암호문
    phone TEXT, -- 전화번호 암호문
    birth_year INTEGER,
    gender VARCHAR(10) CHECK (gender IN ('M', 'F')),
    role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN', 'USER')),
    is_active BOOLEAN NOT NULL, -- 이용 가능 여부; 정지와 탈퇴는 구분하지 않음
    token_version BIGINT NOT NULL DEFAULT 0, -- 변경 시 기존 액세스 토큰 무효화
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE
);

-- 이메일 인증번호와 일회용 인증 토큰
CREATE TABLE IF NOT EXISTS email_verifications (
    email VARCHAR(254) NOT NULL, -- 이메일의 HMAC 조회값
    purpose VARCHAR(20) NOT NULL CHECK (purpose IN ('SIGNUP', 'PASSWORD_RESET')), -- 가입·비밀번호 재설정 구분
    code_hash VARCHAR(64) NOT NULL,
    request_hash VARCHAR(64), -- 재설정 유효 시간 연장을 현재 인증번호 발급 요청에 연결
    token_hash VARCHAR(64), -- 번호 확인 이후 발급한 인증 토큰의 해시
    account_version BIGINT, -- 비밀번호 변경 후 이전 재설정 요청 차단
    sent_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (email, purpose)
);

-- 기존 DB에도 인증 시각과 인증번호 발급 요청 식별자를 보완한다.
ALTER TABLE members ADD COLUMN IF NOT EXISTS email_verified_at TIMESTAMP WITHOUT TIME ZONE;
ALTER TABLE email_verifications ADD COLUMN IF NOT EXISTS request_hash VARCHAR(64);

-- 만료된 인증 요청 정리
CREATE INDEX IF NOT EXISTS ix_email_verifications_expires_at ON email_verifications (expires_at);

-- 전체 서버가 공유하는 시간당 인증 메일 발송 제한
CREATE TABLE IF NOT EXISTS email_verification_mail_quota (
    id SMALLINT PRIMARY KEY CHECK (id = 1), -- 발송량을 관리하는 단일 행
    window_started_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    sent_count INTEGER NOT NULL
);


-- 소셜 로그인 계정
CREATE TABLE IF NOT EXISTS social_accounts (
    social_account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES members(member_id),
    provider VARCHAR(20) NOT NULL,
    provider_user_id VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    UNIQUE (provider, provider_user_id) -- 제공자별 소셜 계정 중복 방지
);


-- 리프레시 토큰
CREATE TABLE IF NOT EXISTS auth_refresh_token (
    refresh_token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL,
    token_hash CHAR(64) NOT NULL UNIQUE, -- 리프레시 토큰 원문 대신 해시 저장
    expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITHOUT TIME ZONE, -- 폐기되지 않은 토큰은 NULL
