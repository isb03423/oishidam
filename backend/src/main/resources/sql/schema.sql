-- 주문번호의 초별 일련번호: 동시 주문도 DB에서 중복 없이 발급한다.
CREATE TABLE IF NOT EXISTS order_number_sequences (
    time_prefix VARCHAR(14) PRIMARY KEY CHECK (time_prefix ~ '^[0-9]{14}$'), -- 한국 시간 yyyyMMddHHmmss
    last_value INTEGER NOT NULL CHECK (last_value BETWEEN 1 AND 9999) -- 해당 초의 마지막 발급 번호
);

-- 주문 및 배송 정보
CREATE TABLE IF NOT EXISTS orders (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES members(member_id),
    order_number VARCHAR(36) NOT NULL UNIQUE, -- 날짜·시간 14자리 + 일련번호 4자리
    request_key VARCHAR(36) NOT NULL, -- 중복 주문 요청 식별자
    request_hash VARCHAR(64) NOT NULL, -- 동일 요청의 주문 내용 비교용 해시
    order_status VARCHAR(30) NOT NULL, -- 결제·배송·취소를 통합한 주문 상태
    items_amount NUMERIC(14, 0) NOT NULL CHECK (items_amount >= 0),
    shipping_fee NUMERIC(14, 0) NOT NULL CHECK (shipping_fee >= 0),
    total_amount NUMERIC(14, 0) NOT NULL CHECK (total_amount = items_amount + shipping_fee), -- 상품 금액과 배송비 합계
    recipient_name TEXT NOT NULL, -- 수령인명 암호문
    recipient_phone TEXT NOT NULL, -- 수령인 연락처 암호문
    postal_code TEXT NOT NULL, -- 우편번호 암호문
    address_line1 TEXT NOT NULL, -- 기본주소 암호문
    address_line2 TEXT, -- 상세주소 암호문
    delivery_memo TEXT, -- 배송메모 암호문
    customs_code TEXT, -- 주문 시 입력한 개인통관고유부호 암호문
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    UNIQUE (member_id, request_key) -- 회원별 동일 주문 요청 중복 방지
);

-- 자동 만료 대상인 결제 대기 주문 조회
CREATE INDEX IF NOT EXISTS ix_orders_pending_expiration
    ON orders (order_id, created_at) WHERE order_status = 'PAYMENT_PENDING';

