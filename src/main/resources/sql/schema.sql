-- 회원
CREATE TABLE IF NOT EXISTS members (
    member_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) UNIQUE,
    password VARCHAR(255), -- 비밀번호 해시; 소셜 전용 계정은 없을 수 있음
    name VARCHAR(100) NOT NULL,
    phone VARCHAR(30),
    birth_year INTEGER,
    gender VARCHAR(10) CHECK (gender IN ('M', 'F')),
    role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN', 'USER')),
    is_active BOOLEAN NOT NULL, -- 이용 가능 여부; 정지와 탈퇴는 구분하지 않음
    token_version BIGINT NOT NULL DEFAULT 0, -- 변경 시 기존 액세스 토큰 무효화
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE
);


-- 소셜 로그인 계정
CREATE TABLE IF NOT EXISTS social_accounts (
    social_account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES members(member_id),
    provider VARCHAR(20) NOT NULL,
    provider_user_id VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    UNIQUE (provider, provider_user_id) -- 제공자별 소셜 계정 중복 방지
);


-- 리프레시 토큰
CREATE TABLE IF NOT EXISTS auth_refresh_token (
    refresh_token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL,
    token_hash CHAR(64) NOT NULL UNIQUE, -- 리프레시 토큰 원문 대신 해시 저장
    expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITHOUT TIME ZONE, -- 폐기되지 않은 토큰은 NULL
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);


-- 로그아웃한 액세스 토큰
CREATE TABLE IF NOT EXISTS revoked_access_tokens (
    token_id VARCHAR(36) PRIMARY KEY,
    expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);


-- 회원 배송지
CREATE TABLE IF NOT EXISTS addresses (
    address_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES members(member_id),
    label VARCHAR(50) NOT NULL,
    recipient_name VARCHAR(100) NOT NULL,
    recipient_phone VARCHAR(30) NOT NULL,
    postal_code VARCHAR(20) NOT NULL,
    address_line1 VARCHAR(255) NOT NULL,
    address_line2 VARCHAR(255),
    is_default BOOLEAN NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE
);

-- 회원별 기본 배송지 중복 방지
CREATE UNIQUE INDEX IF NOT EXISTS ux_addresses_member_default
    ON addresses (member_id)
    WHERE is_default = TRUE;


-- 상품 카테고리
CREATE TABLE IF NOT EXISTS categories (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id BIGINT REFERENCES categories(category_id), -- 최상위 카테고리는 NULL
    name VARCHAR(100) NOT NULL,
    sort_order INTEGER NOT NULL,
    is_active BOOLEAN NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE
);


-- 상품
CREATE TABLE IF NOT EXISTS products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES categories(category_id),
    name VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    brand VARCHAR(100),
    sale_status VARCHAR(20) NOT NULL CHECK (sale_status IN ('DRAFT', 'ON_SALE', 'STOPPED')), -- 작성 중·판매 중·판매 중지
    published_at TIMESTAMP WITHOUT TIME ZONE, -- 최초 판매 시작 시각
    deleted_at TIMESTAMP WITHOUT TIME ZONE, -- 삭제 시각; NULL이면 삭제되지 않음
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE
);


-- 상품 이미지
CREATE TABLE IF NOT EXISTS product_images (
    product_image_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(product_id),
    storage_key VARCHAR(500) NOT NULL, -- 이미지 저장 주소
    alt_text VARCHAR(255),
    sort_order INTEGER NOT NULL,
    is_primary BOOLEAN NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

-- 상품별 대표 이미지 중복 방지
CREATE UNIQUE INDEX IF NOT EXISTS ux_product_images_primary
    ON product_images (product_id)
    WHERE is_primary = TRUE;


-- 상품 옵션 및 재고
CREATE TABLE IF NOT EXISTS product_variants (
    variant_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(product_id),
    sku_code VARCHAR(80) NOT NULL UNIQUE,
    variant_name VARCHAR(200) NOT NULL,
    option_values JSONB NOT NULL, -- 옵션 속성 및 값
    price NUMERIC(14, 0) NOT NULL, -- 옵션 가격, 원 단위
    stock_quantity INTEGER NOT NULL,
    is_active BOOLEAN NOT NULL, -- 고객에게 선택 가능한 옵션인지 여부
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    UNIQUE (product_id, variant_name), -- 상품 내 옵션명 중복 방지
    CONSTRAINT ck_product_variants_nonnegative CHECK (price >= 0 AND stock_quantity >= 0) -- 가격·재고 음수 방지
);


-- 회원 찜 상품
CREATE TABLE IF NOT EXISTS wish_items (
    wish_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES members(member_id),
    product_id BIGINT NOT NULL REFERENCES products(product_id),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    UNIQUE (member_id, product_id) -- 회원별 상품 찜 중복 방지
);


-- 회원 장바구니
CREATE TABLE IF NOT EXISTS cart_items (
    cart_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES members(member_id),
    variant_id BIGINT NOT NULL REFERENCES product_variants(variant_id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    UNIQUE (member_id, variant_id) -- 회원별 동일 옵션 중복 방지
);


-- 주문 및 배송 정보
CREATE TABLE IF NOT EXISTS orders (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES members(member_id),
    order_number VARCHAR(36) NOT NULL UNIQUE,
    request_key VARCHAR(36) NOT NULL, -- 중복 주문 요청 식별자
    request_hash VARCHAR(64) NOT NULL, -- 동일 요청의 주문 내용 비교용 해시
    order_status VARCHAR(30) NOT NULL, -- 결제·배송·취소를 통합한 주문 상태
    items_amount NUMERIC(14, 0) NOT NULL CHECK (items_amount >= 0),
    shipping_fee NUMERIC(14, 0) NOT NULL CHECK (shipping_fee >= 0),
    total_amount NUMERIC(14, 0) NOT NULL CHECK (total_amount = items_amount + shipping_fee), -- 상품 금액과 배송비 합계
    recipient_name VARCHAR(100) NOT NULL,
    recipient_phone VARCHAR(30) NOT NULL,
    postal_code VARCHAR(20) NOT NULL,
    address_line1 VARCHAR(255) NOT NULL,
    address_line2 VARCHAR(255),
    delivery_memo VARCHAR(255),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    UNIQUE (member_id, request_key) -- 회원별 동일 주문 요청 중복 방지
);

-- 주문 시점의 상품 및 옵션 정보
CREATE TABLE IF NOT EXISTS order_items (
    order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(order_id),
    variant_id BIGINT NOT NULL REFERENCES product_variants(variant_id),
    cart_item_id BIGINT, -- 주문 당시 장바구니 항목 식별자; 이전 주문은 NULL 가능
    product_name VARCHAR(200) NOT NULL,
    variant_name VARCHAR(200) NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(14, 0) NOT NULL CHECK (unit_price >= 0),
    UNIQUE (order_id, variant_id) -- 주문 내 동일 옵션 중복 방지
);


-- 주문당 결제 시작 요청
CREATE TABLE IF NOT EXISTS payment_requests (
    payment_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE REFERENCES orders(order_id),
    request_key VARCHAR(36) NOT NULL, -- 결제 시작 요청 식별자
    provider VARCHAR(20) NOT NULL CHECK (provider = 'TOSS'),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE
);

-- 기존 주문 스냅샷에도 장바구니 항목 식별자를 추가한다.
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS cart_item_id BIGINT;

-- 주문별 결제 승인 정보
CREATE TABLE IF NOT EXISTS payment_confirmations (
    payment_confirmation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE REFERENCES orders(order_id),
    payment_key VARCHAR(200) NOT NULL UNIQUE, -- 결제사 결제 식별자
    paid_at TIMESTAMP WITHOUT TIME ZONE, -- 승인 완료 전에는 NULL
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE
);


-- 주문 상태 변경 이력
CREATE TABLE IF NOT EXISTS order_status_histories (
    order_status_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(order_id),
    previous_status VARCHAR(30),
    new_status VARCHAR(30) NOT NULL,
    changed_by BIGINT REFERENCES members(member_id),
    note VARCHAR(255),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE
);

-- 회원별 주문 목록 조회
CREATE INDEX IF NOT EXISTS ix_orders_member_created
    ON orders (member_id, created_at DESC, order_id DESC);


-- 주문 취소 요청 및 완료 정보
CREATE TABLE IF NOT EXISTS order_cancellations (
    order_cancellation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE REFERENCES orders(order_id),
    reason VARCHAR(200) NOT NULL,
    cancelled_at TIMESTAMP WITHOUT TIME ZONE, -- 결제 취소 확인 전에는 NULL
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE
);


-- 주문별 상태 변경 이력 조회
CREATE INDEX IF NOT EXISTS ix_order_status_histories_order
    ON order_status_histories (order_id, order_status_history_id);


-- 주문 상품 리뷰 및 관리자 답변
CREATE TABLE IF NOT EXISTS reviews (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id BIGINT NOT NULL UNIQUE REFERENCES order_items(order_item_id),
    member_id BIGINT NOT NULL REFERENCES members(member_id),
    content TEXT NOT NULL,
    deleted_at TIMESTAMP WITHOUT TIME ZONE, -- 삭제 시각; NULL이면 삭제되지 않음
    answer_content TEXT,
    answered_by BIGINT REFERENCES members(member_id),
    answered_at TIMESTAMP WITHOUT TIME ZONE,
    answer_updated_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    -- 관리자 답변의 내용·작성자·작성/수정 시각을 함께 관리한다.
    CHECK ((answer_content IS NULL AND answered_by IS NULL AND answered_at IS NULL AND answer_updated_at IS NULL)
        OR (answer_content IS NOT NULL AND answered_by IS NOT NULL AND answered_at IS NOT NULL AND answer_updated_at IS NOT NULL))
);
-- 회원별 리뷰 조회
CREATE INDEX IF NOT EXISTS ix_reviews_member ON reviews(member_id);
-- 상품 옵션별 주문 상품 조회
CREATE INDEX IF NOT EXISTS ix_order_items_variant ON order_items(variant_id);

-- 1:1 문의; 제목은 공개하지만 본문과 대화는 권한을 확인한다.
CREATE TABLE IF NOT EXISTS inquiries (
    inquiry_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES members(member_id),
    order_id BIGINT REFERENCES orders(order_id), -- 연결된 주문이 없으면 NULL
    title VARCHAR(200) NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('OPEN', 'ANSWERED')), -- 답변 대기·답변 완료
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE
);
-- 회원별 문의를 최신순으로 조회
CREATE INDEX IF NOT EXISTS ix_inquiries_member ON inquiries(member_id, inquiry_id DESC);

-- 고객과 관리자가 작성한 문의 대화 메시지
CREATE TABLE IF NOT EXISTS inquiry_messages (
    inquiry_message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inquiry_id BIGINT NOT NULL REFERENCES inquiries(inquiry_id),
    sender_member_id BIGINT NOT NULL REFERENCES members(member_id),
    content TEXT NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE
);
-- 문의별 대화 내용을 작성 순서대로 조회
CREATE INDEX IF NOT EXISTS ix_inquiry_messages_inquiry ON inquiry_messages(inquiry_id, inquiry_message_id);
