-- 1:1 문의; 게시글당 관리자 답변 하나만 등록하며 본문과 답변은 권한을 확인한다.
CREATE TABLE IF NOT EXISTS inquiries (
    inquiry_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES members(member_id),
    order_id BIGINT REFERENCES orders(order_id), -- 연결된 주문이 없으면 NULL
    title VARCHAR(200) NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('OPEN', 'ANSWERED')), -- 답변 대기·답변 완료
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE
);
-- 회원별 문의를 최신순으로 조회
CREATE INDEX IF NOT EXISTS ix_inquiries_member ON inquiries(member_id, inquiry_id DESC);

-- 최초 문의 본문과 관리자 답변 (서비스에서 문의 행 잠금으로 중복 답변 방지)
