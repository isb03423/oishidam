-- 회원
CREATE TABLE IF NOT EXISTS members (
    member_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) UNIQUE,
    password VARCHAR(255),
    name VARCHAR(100) NOT NULL,
    phone VARCHAR(30),
    birth_year INTEGER,
    gender VARCHAR(10) CHECK (gender IN ('M', 'F')),
    role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN', 'USER')),
    is_active BOOLEAN NOT NULL,
    token_version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE
);


-- 소셜 로그인 계정
CREATE TABLE IF NOT EXISTS social_accounts (
    social_account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES members(member_id),
    provider VARCHAR(20) NOT NULL,
    provider_user_id VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    UNIQUE (provider, provider_user_id)
);


-- 리프레시 토큰
CREATE TABLE IF NOT EXISTS auth_refresh_token (
    refresh_token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL,
    token_hash CHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);


-- 로그아웃한 액세스 토큰
CREATE TABLE IF NOT EXISTS revoked_access_tokens (
    token_id VARCHAR(36) PRIMARY KEY,
    expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);


-- 회원 배송지
CREATE TABLE IF NOT EXISTS addresses (
    address_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES members(member_id),
    label VARCHAR(50) NOT NULL,
    recipient_name VARCHAR(100) NOT NULL,
    recipient_phone VARCHAR(30) NOT NULL,
    postal_code VARCHAR(20) NOT NULL,
    address_line1 VARCHAR(255) NOT NULL,
    address_line2 VARCHAR(255),
    is_default BOOLEAN NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE
);

-- 회원별 기본 배송지 중복 방지
CREATE UNIQUE INDEX IF NOT EXISTS ux_addresses_member_default
    ON addresses (member_id)
    WHERE is_default = true;


-- 상품 카테고리
CREATE TABLE IF NOT EXISTS categories (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id BIGINT REFERENCES categories(category_id),
    name VARCHAR(100) NOT NULL,
    sort_order INTEGER NOT NULL,
    is_active BOOLEAN NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE
);


-- 상품
CREATE TABLE IF NOT EXISTS products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES categories(category_id),
    name VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    brand VARCHAR(100),
    sale_status VARCHAR(20) NOT NULL CHECK (sale_status IN ('DRAFT', 'ON_SALE', 'STOPPED')),
    published_at TIMESTAMP WITHOUT TIME ZONE,
    deleted_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE
);


-- 상품 이미지
CREATE TABLE IF NOT EXISTS product_images (
    product_image_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(product_id),
    storage_key VARCHAR(500) NOT NULL,
    alt_text VARCHAR(255),
    sort_order INTEGER NOT NULL,
    is_primary BOOLEAN NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

-- 상품별 대표 이미지 중복 방지
CREATE UNIQUE INDEX IF NOT EXISTS ux_product_images_primary
    ON product_images (product_id)
    WHERE is_primary = true;


-- 상품 옵션 및 재고
CREATE TABLE IF NOT EXISTS product_variants (
    variant_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(product_id),
    sku_code VARCHAR(80) NOT NULL UNIQUE,
    variant_name VARCHAR(200) NOT NULL,
    option_values JSONB NOT NULL,
    price NUMERIC(14, 0) NOT NULL,
    stock_quantity INTEGER NOT NULL,
    is_active BOOLEAN NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    UNIQUE (product_id, variant_name),
    CONSTRAINT ck_product_variants_nonnegative CHECK (price >= 0 AND stock_quantity >= 0)
);


-- 회원 장바구니
CREATE TABLE IF NOT EXISTS cart_items (
    cart_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES members(member_id),
    variant_id BIGINT NOT NULL REFERENCES product_variants(variant_id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    UNIQUE (member_id, variant_id)
);
